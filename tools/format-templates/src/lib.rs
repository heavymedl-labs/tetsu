//! Formats Tetsu's HTML templates with `markup_fmt` (ADR-0083), as Jinja, which Askama's syntax follows, in strict
//! whitespace mode, which never adds or removes whitespace a browser would show. Lines run to 120 columns, indented
//! by two spaces. Template tags keep their contents as written, since those are Rust.

use std::borrow::Cow;
use std::path::{Path, PathBuf};

use markup_fmt::config::{FormatOptions, LanguageOptions, LayoutOptions, WhitespaceSensitivity};
use markup_fmt::{Language, format_text};

/// `source` formatted, or why it could not be. A generated template, one whose first line says it is, is its
/// generator's to write, so it stays as written.
///
/// # Errors
/// Fails if `markup_fmt` cannot parse `source`.
pub fn format(source: &str) -> Result<String, String> {
    if source
        .lines()
        .next()
        .is_some_and(|first| first.contains("Generated by"))
    {
        return Ok(source.to_string());
    }
    let options = FormatOptions {
        layout: LayoutOptions {
            print_width: 120,
            ..LayoutOptions::default()
        },
        language: LanguageOptions {
            whitespace_sensitivity: WhitespaceSensitivity::Strict,
            ..LanguageOptions::default()
        },
    };
    // Templates hold no inline scripts or styles, which markup_fmt would hand to another formatter, so any it
    // meets stay as written.
    format_text(source, Language::Jinja, &options, |code, _| {
        Ok(Cow::Borrowed(code))
    })
    .map_err(|error| format!("{error:?}"))
}

/// Formats every template under `root`, or with `check` only finds those not formatted, and says what is wrong
/// with each one that is not, or could not be, formatted.
#[must_use]
pub fn run(root: &Path, check: bool) -> Vec<String> {
    match templates(root) {
        Ok(paths) => paths
            .iter()
            .filter_map(|path| tidy(path, check).err())
            .collect(),
        Err(error) => vec![format!("cannot list the templates: {error}")],
    }
}

/// Formats the template at `path`, or with `check` fails if it is not formatted.
fn tidy(path: &Path, check: bool) -> Result<(), String> {
    let shown = path.display();
    let source = std::fs::read_to_string(path).map_err(|error| format!("{shown}: {error}"))?;
    let formatted = format(&source).map_err(|error| format!("{shown}: {error}"))?;
    if formatted == source {
        Ok(())
    } else if check {
        Err(format!(
            "{shown} is not formatted. Run cargo run -p tetsu-format-templates"
        ))
    } else {
        std::fs::write(path, formatted).map_err(|error| format!("{shown}: {error}"))
    }
}

/// The folders of drawings: inline SVG, which the minifier sends as written, so formatting would spread each shape
/// over several lines and grow every page that shows them. They stay as written (ADR-0083).
const DRAWINGS: [&str; 2] = [
    "crates/tetsu/templates/art",
    "crates/tetsu/templates/home/panels",
];

/// Every HTML template under `root`'s `crates` and `web` folders, in a folder named `templates` at any depth,
/// sorted, except the drawings.
///
/// # Errors
/// Fails if a folder cannot be read.
pub fn templates(root: &Path) -> std::io::Result<Vec<PathBuf>> {
    let mut found = Vec::new();
    for top in ["crates", "web"] {
        walk(&root.join(top), false, &mut found)?;
    }
    found.retain(|path| {
        !DRAWINGS
            .iter()
            .any(|drawings| path.starts_with(root.join(drawings)))
    });
    found.sort();
    Ok(found)
}

/// Adds the HTML files under `folder` to `found`, counting them only within a `templates` folder.
fn walk(folder: &Path, within: bool, found: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(folder)? {
        let path = entry?.path();
        if path.is_dir() {
            walk(&path, within || path.ends_with("templates"), found)?;
        } else if within && path.extension().is_some_and(|ext| ext == "html") {
            found.push(path);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A folder in the system's temporary folder, named as the workspace's other scratch files are, so a sweep
    /// finds any left behind, and removed when dropped.
    struct Scratch(PathBuf);

    impl Drop for Scratch {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    /// A root holding one template, in a nested `templates` folder, with `source`.
    fn root_with(name: &str, source: &str) -> (Scratch, PathBuf) {
        let root =
            Scratch(std::env::temp_dir().join(format!("tetsu-{}-{name}", std::process::id())));
        let folder = root.0.join("crates/a/templates/mail");
        std::fs::create_dir_all(&folder).unwrap();
        std::fs::create_dir_all(root.0.join("web")).unwrap();
        let template = folder.join("page.html");
        std::fs::write(&template, source).unwrap();
        (root, template)
    }

    /// Checking finds an unformatted template and leaves it; formatting rewrites it, after which checking passes.
    #[test]
    fn checking_finds_what_formatting_fixes() {
        let (root, template) = root_with("format-run", "<ul>\n<li>x</li>\n</ul>\n");
        let problems = run(&root.0, true);
        assert_eq!(problems.len(), 1, "{problems:?}");
        assert!(problems[0].ends_with("is not formatted. Run cargo run -p tetsu-format-templates"));
        assert_eq!(
            std::fs::read_to_string(&template).unwrap(),
            "<ul>\n<li>x</li>\n</ul>\n"
        );
        assert_eq!(run(&root.0, false), Vec::<String>::new());
        assert_eq!(
            std::fs::read_to_string(&template).unwrap(),
            "<ul>\n  <li>x</li>\n</ul>\n"
        );
        assert_eq!(run(&root.0, true), Vec::<String>::new());
    }

    /// A template that does not parse, or a root with nothing to list, is reported rather than skipped.
    #[test]
    fn what_cannot_be_formatted_is_reported() {
        let (root, template) = root_with("format-broken", "<div {% if %}");
        let problems = run(&root.0, false);
        assert_eq!(problems.len(), 1, "{problems:?}");
        assert!(
            problems[0].starts_with(&format!("{}: ", template.display())),
            "{problems:?}"
        );
        let missing = run(&root.0.join("nowhere"), true);
        assert_eq!(missing.len(), 1);
        assert!(
            missing[0].starts_with("cannot list the templates: "),
            "{missing:?}"
        );
    }

    #[test]
    fn nesting_is_indented_and_a_formatted_template_stays_as_it_is() {
        let formatted = format("<ul>\n<li>{{ name }}</li>\n</ul>\n").unwrap();
        assert_eq!(formatted, "<ul>\n  <li>{{ name }}</li>\n</ul>\n");
        assert_eq!(format(&formatted).unwrap(), formatted);
    }

    /// Rust inside a tag, such as a character literal, is left as written, and text keeps the whitespace a browser
    /// would show.
    #[test]
    fn tags_keep_their_rust_and_text_keeps_its_spacing() {
        let source = "<p>{% if k == 't' %}<b>KM</b>, {{ name }}{% endif %}</p>\n";
        let formatted = format(source).unwrap();
        assert!(formatted.contains("{% if k == 't' %}"), "{formatted}");
        assert!(formatted.contains("<b>KM</b>, {{ name }}"), "{formatted}");
    }

    /// A generated template is its generator's to write, so it stays as written.
    #[test]
    fn a_generated_template_stays_as_written() {
        let source = "{#- Generated by scripts/generate_brand.py; do not edit. -#}\n<ul>\n<li>x</li>\n</ul>\n";
        assert_eq!(format(source).unwrap(), source);
    }

    /// A line of up to 120 columns stays whole.
    #[test]
    fn lines_run_to_120_columns() {
        let line = format!("<p class=\"{}\">x</p>\n", "a ".repeat(50).trim_end());
        assert!((90..=120).contains(&line.trim_end().len()));
        assert_eq!(format(&line).unwrap(), line);
    }

    /// Wrapping a long run of inline text never puts whitespace where the template had none, so the page reads the
    /// same.
    #[test]
    fn wrapping_adds_no_whitespace_a_browser_would_show() {
        let words = "word ".repeat(30);
        let source = format!("<p><b>KM</b><span class=\"sr-only\">, {words}</span>end</p>\n");
        let formatted = format(&source).unwrap();
        let joined = |text: &str| text.split_whitespace().collect::<String>();
        assert_eq!(joined(&formatted), joined(&source));
        assert!(formatted.contains("<b>KM</b><span"), "{formatted}");
        assert!(formatted.contains("</span>end</p>"), "{formatted}");
    }

    #[test]
    fn a_template_that_does_not_parse_is_an_error() {
        assert!(format("<div {% if %}").is_err());
    }

    /// Templates in every crate and in `web`, nested or not, and nothing else.
    #[test]
    fn templates_are_every_html_file_in_a_templates_folder() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let found = templates(&root).unwrap();
        let named = |path: &str| found.contains(&root.join(path));
        assert!(named("web/templates/page.html"));
        assert!(named("crates/identity/templates/mail/invite.html"));
        assert!(named("crates/tetsu/templates/home/week.html"));
        assert!(!named("crates/tetsu/templates/art/board.html"));
        assert!(!named("crates/tetsu/templates/home/panels/layouts.html"));
        assert!(!named("crates/tenancy/templates/theme.css"));
        assert!(
            found
                .iter()
                .all(|path| path.extension().is_some_and(|ext| ext == "html"))
        );
        assert!(found.is_sorted());
    }
}
